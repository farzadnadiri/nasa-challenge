import { Container } from '@cloudflare/containers'

// FastAPI science backend (backend/Dockerfile). One named instance: job progress lives in
// its memory, so every poll for the same view must reach the same container.
export class SpherexApi extends Container<Env> {
  defaultPort = 8080
  sleepAfter = '30m'
  enableInternet = true // Gaia, CDS and S3 are reached directly from the container
  pingEndpoint = '/api/health'

  constructor(ctx: DurableObjectState<{}>, env: Env) {
    super(ctx, env)
    // IRSA refuses connections from the container network but not from the Worker runtime,
    // so the container reaches IRSA through this Worker's /api/_irsa/ proxy.
    this.envVars = {
      IRSA_BASE: `${env.PUBLIC_URL}/api/_irsa/`,
      IRSA_PROXY_KEY: env.IRSA_PROXY_KEY,
    }
  }
}

// Env (API, CACHE, ASSETS, PUBLIC_URL, IRSA_PROXY_KEY) is generated by `npm run types`.

const CACHEABLE = new Set(['/api/frames', '/api/photometry', '/api/gaia'])
const TTL_MS = 7 * 24 * 3600 * 1000 // SPHEREx ingests weekly

const IRSA = 'https://irsa.ipac.caltech.edu/'
// Only what the backend needs: image search and SPHEREx image cutouts. Never an open proxy.
const IRSA_ALLOWED = [/^SIA$/, /^TAP\/sync$/, /^ibe\/data\/spherex\/[\w./-]+\.fits$/]

// Keyed by container generation too, so a backend change never serves results from the old pipeline.
function cacheKey(url: URL, gen: string): string {
  const params = [...url.searchParams.entries()].sort(([a], [b]) => a.localeCompare(b))
  return `g${gen}${url.pathname}?${new URLSearchParams(params)}`
}

async function proxyIrsa(request: Request, url: URL, env: Env): Promise<Response> {
  if (!env.IRSA_PROXY_KEY || request.headers.get('x-proxy-key') !== env.IRSA_PROXY_KEY) {
    return new Response('Forbidden', { status: 403 })
  }
  const path = url.pathname.slice('/api/_irsa/'.length)
  if (!IRSA_ALLOWED.some((re) => re.test(path)) || path.includes('..')) {
    return new Response('Not allowed', { status: 404 })
  }
  const upstream = await fetch(IRSA + path + url.search, {
    method: request.method,
    headers: request.method === 'POST' ? { 'content-type': request.headers.get('content-type') ?? '' } : undefined,
    body: request.method === 'POST' ? request.body : undefined,
  })
  // Stream the body straight through (cutouts are ~4 MB each).
  return new Response(upstream.body, {
    status: upstream.status,
    headers: { 'content-type': upstream.headers.get('content-type') ?? 'application/octet-stream' },
  })
}

export default {
  async fetch(request: Request, env: Env, ctx: ExecutionContext): Promise<Response> {
    const url = new URL(request.url)
    if (!url.pathname.startsWith('/api/')) return env.ASSETS.fetch(request)
    if (url.pathname.startsWith('/api/_irsa/')) return proxyIrsa(request, url, env)
    if (request.method !== 'GET') return new Response('Method not allowed', { status: 405 })

    const cacheable = CACHEABLE.has(url.pathname)
    const key = cacheKey(url, env.CONTAINER_GEN)
    if (cacheable) {
      const hit = await env.CACHE.get(key)
      const saved = Number(hit?.customMetadata?.saved ?? 0)
      if (hit && Date.now() - saved < TTL_MS) {
        return new Response(hit.body, {
          headers: { 'content-type': 'application/json', 'cache-control': 'public, max-age=3600', 'x-cache': 'HIT' },
        })
      }
    }

    const container = env.API.getByName(`api-${env.CONTAINER_GEN}`)
    await container.startAndWaitForPorts()
    const res = await container.fetch(request)

    // Store only finished results; in-progress responses change on every poll.
    if (cacheable && res.ok && res.headers.get('x-complete') === 'true') {
      const body = await res.arrayBuffer()
      ctx.waitUntil(env.CACHE.put(key, body, {
        httpMetadata: { contentType: 'application/json' },
        customMetadata: { saved: String(Date.now()) },
      }))
      return new Response(body, { status: res.status, headers: res.headers })
    }
    return res
  },
} satisfies ExportedHandler<Env>
